public class KompNaOsoba {
    public static void main(String[] args) {
        int komp = 17;
        int osoba = 11;

        double kompNaOsoba = (double)komp / osoba;

        System.out.println("Ilość komputerów na osobę: " +
                kompNaOsoba);
    }
}
